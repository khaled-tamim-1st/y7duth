async function seed() {
  const dbPath = path.resolve(process.cwd(), 'local-data', 'pglite');
  const db = new PGlite(dbPath);

  console.log('Seeding initial 4 batch articles into local database...');
  for (const art of articles) {
    try {
      await db.query(`
        INSERT INTO articles (slug, title, excerpt, content, category, location, author_name, author_role, cover_image, status, read_time, published_at, created_at, updated_at)
        VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9, 'published', $10, NOW(), NOW(), NOW())
        ON CONFLICT (slug) DO UPDATE SET
          title = EXCLUDED.title,
          excerpt = EXCLUDED.excerpt,
          content = EXCLUDED.content,
          category = EXCLUDED.category,
          location = EXCLUDED.location,
          author_name = EXCLUDED.author_name,
          author_role = EXCLUDED.author_role,
          cover_image = EXCLUDED.cover_image,
          read_time = EXCLUDED.read_time,
          status = 'published';
      `, [art.slug, art.title, art.excerpt, art.content, art.category, art.location, art.authorName, art.authorRole, art.coverImage, art.readTime]);
      console.log('Inserted/Updated:', art.slug);
    } catch (err) {
      console.error('Error inserting', art.slug, err);
    }
  }
  console.log('Finished seeding batch 1.');
  process.exit(0);
}

