async function applySchedule() {
  const dbPath = path.resolve(process.cwd(), 'local-data', 'pglite');
  const db = new PGlite(dbPath);

  console.log('--- بدء جدولة المقالات العشرين لقسم أهل الديرة ---');
  console.log('الفترة المحددة: من 10 نوفمبر 2026 إلى 31 ديسمبر 2026\n');

  for (let i = 0; i < scheduleDates.length; i++) {
    const item = scheduleDates[i];
    const targetDate = new Date(item.date);

    await db.query(`
      UPDATE articles
      SET 
        status = 'scheduled',
        scheduled_for = $1,
        published_at = NULL,
        updated_at = NOW()
      WHERE slug = $2
    `, [targetDate.toISOString(), item.slug]);

    console.log(`[${i + 1}/20] جدولة: ${item.slug} -> ${targetDate.toLocaleDateString('ar-KW', { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' })} (${targetDate.toLocaleTimeString('ar-KW')})`);
  }

  const res = await db.query(`
    SELECT title, category, status, scheduled_for 
    FROM articles 
    WHERE category = 'أهل الديرة' 
    ORDER BY scheduled_for ASC;
  `);

  console.log('\n--- ملخص المقالات المجدولة في قاعدة البيانات ---');
  console.log(`إجمالي المقالات المجدولة: ${res.rows.length}`);
  res.rows.forEach((r, idx) => {
    const d = new Date(r.scheduled_for);
    console.log(`${idx + 1}. [${r.status}] ${r.title} | التاريخ: ${d.toISOString().slice(0, 10)}`);
  });

  process.exit(0);
}

applySchedule();
